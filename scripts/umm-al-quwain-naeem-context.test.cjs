const assert=require('node:assert/strict'),fs=require('node:fs'),path=require('node:path');
const read=file=>fs.readFileSync(path.join(__dirname,'..',file),'utf8');
const presence=read('lib/alNaeemPresence.js');
const geo=read('lib/alNaeemLocalSeo.js');
const discovery=read('components/provider/AlNaeemLocalDiscovery.js');
const company=read('components/provider/AlNaeemPresencePage.js');
const taxonomy=read('data/siteTaxonomy.js');
const list=JSON.parse(read('data/northernDirectoryContent.js').match(/^export const NORTHERN_LOCALITIES=(.+);$/m)[1])['umm-al-quwain'];
assert.ok(list.length>=15,'published UAQ district list must remain unchanged');
